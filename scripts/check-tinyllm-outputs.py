"""Check that the TinyLLM notebooks are up to date and that quoted output matches them.

1. Each docs/public/tinyllm/notebooks/<slug>.ipynb must have the same cells as
   docs/public/tinyllm/code/<slug>.py (otherwise the script was edited without
   re-running scripts/build-tinyllm-code.py).

2. Every ```text block in docs/tinyllm/<slug>.md is treated as quoted output of
docs/public/tinyllm/code/<slug>.py. Each non-empty line must appear in the saved
outputs of docs/public/tinyllm/notebooks/<slug>.ipynb (generated by
scripts/build-tinyllm-code.py). Whitespace runs are compared as a single space.

A block that is not program output (for example a hand-written illustration)
can be skipped by putting this comment on the line right before it:

    <!-- output-check: skip -->

Usage: python scripts/check-tinyllm-outputs.py [slug ...]
Exit code 1 if any quoted line is missing.
"""

from pathlib import Path
import importlib.util
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs/tinyllm"
NOTEBOOKS = ROOT / "docs/public/tinyllm/notebooks"
CODE = ROOT / "docs/public/tinyllm/code"
_spec = importlib.util.spec_from_file_location("build_tinyllm_code", ROOT / "scripts/build-tinyllm-code.py")
build = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(build)
SKIP = "<!-- output-check: skip -->"
BLOCK = re.compile(r"(?P<before>[^\n]*)\n```text\n(?P<body>.*?)\n```", re.S)


def norm(line: str) -> str:
    return re.sub(r"\s+", " ", line).strip()


def notebook_lines(path: Path) -> set[str]:
    nb = json.loads(path.read_text(encoding="utf-8"))
    lines: set[str] = set()
    for cell in nb["cells"]:
        for out in cell.get("outputs", []):
            text = out.get("text") or out.get("data", {}).get("text/plain") or []
            text = "".join(text) if isinstance(text, list) else text
            lines.update(norm(l) for l in text.splitlines() if l.strip())
    return lines


def stale(nb: Path) -> bool:
    script = CODE / f"{nb.stem}.py"
    cells = json.loads(nb.read_text(encoding="utf-8"))["cells"]
    saved = [(c["cell_type"], "".join(c["source"]) if isinstance(c["source"], list) else c["source"]) for c in cells]
    return not script.exists() or saved != build.split_cells(script)


def check(md: Path) -> list[str]:
    nb = NOTEBOOKS / f"{md.stem}.ipynb"
    if not nb.exists():
        return []
    problems = [f"{nb.relative_to(ROOT)}: 与 {md.stem}.py 不一致，请运行 python scripts/build-tinyllm-code.py {md.stem}"] if stale(nb) else []
    outputs = notebook_lines(nb)
    text = md.read_text(encoding="utf-8")
    for m in BLOCK.finditer(text):
        if m.group("before").strip() == SKIP:
            continue
        line_no = text[: m.start("body")].count("\n") + 1
        for k, line in enumerate(m.group("body").splitlines()):
            if line.strip() and norm(line) not in outputs:
                problems.append(f"{md.relative_to(ROOT)}:{line_no + k}: {line.strip()}")
    return problems


def main() -> None:
    wanted = set(sys.argv[1:])
    files = sorted(p for p in DOCS.glob("*.md") if not wanted or p.stem in wanted)
    problems = [p for md in files for p in check(md)]
    checked = sum(1 for md in files if (NOTEBOOKS / f"{md.stem}.ipynb").exists())
    for p in problems:
        print("problem:", p)
    print(f"checked {checked} chapters, {len(problems)} problems")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
